#!/usr/bin/env python3
"""Generate tiny Go proving metadata from authenticated Core resources; never vendor circuits.

Usage: sync-reference.py [--proving-only] [legacy_ts_root] [core_root]
       --resource-dir CORE_OUTPUT [--index-sha256 REVIEWED_RELEASE_PIN]
Core resources are generated by Core scripts/prover-assets.mjs. Provenance resources are synchronized separately.
"""
import argparse, hashlib, json, pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--proving-only', action='store_true')
p.add_argument('legacy_ts_root', nargs='?', type=pathlib.Path, default=root.parent/'invisi-sdk-ts')
p.add_argument('core_root', nargs='?', type=pathlib.Path, default=root.parent/'invisi-core')
p.add_argument('--periphery-root', type=pathlib.Path, help='Optional explicit checkout cross-check; authenticated catalog is sufficient')
p.add_argument('--resource-dir', required=True, type=pathlib.Path)
p.add_argument('--index-sha256')
p.add_argument('--legacy-combined', action='store_true', help='Read an explicitly reviewed historical combined catalog')
a = p.parse_args()
def require(ok, message):
    if not ok: raise ValueError(message)
def recursive_metadata(binary,vk,commitment):
    modulus=21888242871839275222246405745257275088548364400416034343698204186575808495617
    require(len(binary)==115*32 and len(vk['vk'])==115,'recursive VK width mismatch')
    words=[int.from_bytes(binary[i:i+32],'big') for i in range(0,len(binary),32)]
    require(all(word<modulus for word in words),'noncanonical recursive VK field')
    require(all(isinstance(word,str) and re.fullmatch(r'0x[0-9a-fA-F]{64}',word) for word in vk['vk']),'noncanonical recursive VK JSON field')
    require(words==[int(word,16) for word in vk['vk']],'recursive VK binary/JSON mismatch')
    require(isinstance(vk['hash'],str) and re.fullmatch(r'0x[0-9a-fA-F]{64}',vk['hash']) and int(vk['hash'],16)<modulus,'noncanonical recursive key hash')
    require(re.fullmatch(r'0x[0-9a-fA-F]{64}',commitment) and int(commitment,16)<modulus,'noncanonical recursive key commitment')
    return {'keyHash':vk['hash'],'innerVkCommitment':commitment}
def digest(data): return hashlib.sha256(data).hexdigest()
def compact(value): return json.dumps(value, separators=(',', ':'), ensure_ascii=False).encode()
def safe_read(base, name):
    rel = pathlib.PurePosixPath(name)
    require(not rel.is_absolute() and '..' not in rel.parts and '\\' not in name, 'unsafe resource path')
    dest = (base/str(rel)).resolve()
    require(dest.is_relative_to(base.resolve()), 'resource escaped source directory')
    return dest.read_bytes()
pins_text = (root/'prover/native/resource_pin.go').read_text() if (root/'prover/native/resource_pin.go').exists() else ''
def current_pin(name, fallback):
    match = re.search(r'const '+name+r'\s*=\s*"([0-9a-f]{64})"', pins_text)
    return match[1] if match else fallback
core_pin = current_pin('resourceIndexSHA256','85a5d1dffe40fc965ab4345a28b632f463c3ad861c44d5845850fbc7447fd8f6')
provenance_pin = current_pin('ProvenanceResourceIndexSHA256','8d5a3e60e3e5cbe315150511207d7aff67f4e2924148d396b67d82017ecd1f1c')
legacy_pin = 'ca3ee827c620b1e25d87d1b880549f8cec4be4970f26ea0ab5993dc2db4c827c'
pin = a.index_sha256 or (legacy_pin if a.legacy_combined else core_pin)
require(re.fullmatch('[0-9a-f]{64}', pin), 'invalid resource index pin')
raw = safe_read(a.resource_dir, 'index.json')
require(digest(raw)==pin, 'untrusted resource index')
index = json.loads(raw)
require(index['format']=='invisi.prover-assets.v1' and index['bbVersion']=='6.0.0' and index['noirVersion']=='1.0.0', 'unsupported resource version')
if not a.legacy_combined:
    require(all(name.startswith('circuits/') for name in index['files']), 'Core-only resource catalog required; legacy must be explicit')
def asset(name):
    # The combined circuit belongs to a separate reviewed resource set. Its tiny
    # metadata is regenerated from the local Core compiler output, never the base set.
    if a.legacy_combined and name.startswith('circuits/create_credit_initial_payment.'):
        entry=next(e for e in json.loads(safe_read(a.core_root,'circuits/credit/manifest.json'))['entries'] if e['name']=='create_credit_initial_payment')
        if name.endswith('.json'): return safe_read(a.core_root,entry['artifact'])
        require(name.endswith('.evm.vk'),'unsupported combined circuit target')
        raw=safe_read(a.core_root,entry['direct']['vk'])
        require(digest(raw)==entry['direct']['vkSha256'],'combined VK identity mismatch')
        return raw
    entry=index['files'][name]
    ext='.vk' if name.endswith('/vk') else pathlib.PurePosixPath(name).suffix
    require(re.fullmatch('[0-9a-f]{64}',entry['sha256']) and ext in ('.json','.vk'), 'invalid object identity')
    data=safe_read(a.resource_dir,entry['sha256']+ext)
    require(len(data)==entry['size'] and digest(data)==entry['sha256'], 'resource checksum mismatch: '+name)
    return data
layouts, recursive = {}, {}
credit_manifest_sha=''
for family, version, fmt in [('transact',4,7),('credit',8,9)]:
    manifest_raw=safe_read(a.core_root,f'circuits/{family}/manifest.json')
    manifest=json.loads(manifest_raw)
    require(manifest['complete'] and manifest['version']==version and manifest['formatVersion']==fmt and manifest['bbVersion']=='6.0.0', 'unsupported Core manifest')
    for name, sha in manifest['dependencies'].items(): require(digest(safe_read(a.core_root,name))==sha,'stale source '+name)
    if family=='credit': credit_manifest_sha=digest(manifest_raw)
    for entry in manifest['entries']+manifest.get('aggregates',[]):
        name=entry['name']; compiled=json.loads(asset('circuits/'+name+'.json'))
        require(digest(compact({'noirVersion':compiled['noir_version'],'abi':compiled['abi'],'bytecode':compiled['bytecode']}))==entry['artifactSha256'], 'artifact identity mismatch')
        keys={}
        for key in [entry.get('direct',entry),entry.get('recursive')]:
            if not key:continue
            require(digest(asset('circuits/'+name+'.'+key['target']+'.vk'))==key['vkSha256'], 'VK identity mismatch')
            keys[key['target']]=key['vkSha256']
            if key['target']=='noir-recursive':
                vkraw=safe_read(a.core_root,key['vkJson']);require(digest(vkraw)==key['vkJsonSha256'],'VK JSON identity mismatch');vk=json.loads(vkraw)
                binary=asset('circuits/'+name+'.'+key['target']+'.vk')
                recursive[str(entry['capacity'])]=recursive_metadata(binary,vk,key['innerVkCommitment'])
        params=compiled['abi']['parameters']
        def width(typ):
            if typ['kind']=='array':return typ['length']*width(typ['type'])
            if typ['kind']=='struct':return sum(width(field['type']) for field in typ['fields'])
            if typ['kind']=='tuple':return sum(width(item) for item in typ['fields'])
            require(typ['kind'] in ('field','integer','boolean'), 'unsupported public ABI type')
            return 1
        require(sum(width(v['type']) for v in params if v['visibility']=='public')==entry['publicInputCount'], 'public width differs from authenticated ABI')
        layouts[name]={'artifactSha256':entry['artifactSha256'],'keys':keys,'publicInputCount':entry['publicInputCount'],'public':[{'name':v['name'],'count':v['type']['length'] if v['type']['kind']=='array' else 1,'array':v['type']['kind']=='array'} for v in params if v['visibility']=='public'],'private':[v['name'] for v in params if v['visibility']!='public']}
require(len(layouts)==78 and len(recursive)==10,'incomplete proving family')
# Optional source cross-check does not make Core synchronization depend on Periphery.
if a.periphery_root is not None:
    require(digest(safe_read(a.periphery_root,'circuits/provenance/manifest.json'))=='6107789c5c0d24c4130bff05da6d389336feb5ccb247c4030eae5198ab05d762','Periphery checkout manifest mismatch')
generated_pins = '// Code generated by scripts/sync-reference.py; DO NOT EDIT.\npackage native\n\n'
for name, value in [('resourceIndexSHA256',core_pin if a.legacy_combined else pin),('ProvenanceResourceIndexSHA256',provenance_pin),('LegacyResourceIndexSHA256',legacy_pin),('InitialPaymentResourceIndexSHA256','9161f92f5789d8eedae15b23fa2651d5399f64ff8fbfc8de6f3f683f0d93be36')]:
    generated_pins += 'const '+name+' = '+json.dumps(value)+'\n'
outputs={'prover/witness-layouts.json':json.dumps(layouts,indent=2)+'\n','prover/recursive-key.json':json.dumps(recursive,indent=2)+'\n','prover/native/resource_pin.go':generated_pins,'protocol/release/current.go':'// Code generated by scripts/sync-reference.py; DO NOT EDIT.\npackage release\n\nconst CreditManifestVersion = 8\nconst CreditFormatVersion = 9\nconst UserManifestVersion = 4\nconst UserFormatVersion = 7\nconst AggregateFormatVersion = 10\nconst CreditManifestSHA256 = '+json.dumps(credit_manifest_sha)+'\n'}
if not a.proving_only:
    for name in ('measured-model.json','model-validation.json','initial-payment-measurements.json'):
        outputs['protocol/gas/data/'+name]=safe_read(a.legacy_ts_root,'packages/protocol/src/gas/data/'+name).decode()
for name,data in outputs.items():(root/name).write_text(data)
print('Synced authenticated tiny proving metadata and fixed resource index pin; circuit assets remain external')
