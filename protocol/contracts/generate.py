#!/usr/bin/env python3
"""Generate pure ABI contracts and RPC bindings from the same compiler artifacts."""
import argparse, json, os, pathlib, re, shutil, subprocess, tempfile
HERE = pathlib.Path(__file__).resolve().parent
SDK = HERE.parents[1]
p = argparse.ArgumentParser()
p.add_argument('--protocol-root', type=pathlib.Path, default=pathlib.Path(os.environ.get('INVISI_PROTOCOL_ROOT', str(SDK.parent / 'invisi-protocol'))))
a = p.parse_args()
abigen = os.environ.get('ABIGEN') or shutil.which('abigen') or str(pathlib.Path.home() / 'go/bin/abigen')
network = SDK / 'rpc/contracts'
network.mkdir(exist_ok=True)
names = {'InvisiProtocol': 'invisi_protocol', 'InvisiFactory': 'invisi_factory', 'VerifierRouter': 'verifier_router', 'CreditVerifierRouter': 'credit_verifier_router', 'IERC20': 'ierc20', 'InvisiAddressRegistry': 'invisi_address_registry'}
with tempfile.TemporaryDirectory(prefix='invisi-bindings-') as tmp:
    for name, stem in names.items():
        source = a.protocol_root / 'contracts/out' / (name + '.sol') / (name + '.json')
        if source.exists():
            artifact = json.loads(source.read_text())
            abi = artifact['abi']
        elif name == 'IERC20':
            abi = json.loads((HERE / 'abi' / f'{name}.abi.json').read_text())
        else:
            raise ValueError('missing compiled artifact: ' + str(source))
        if not isinstance(abi, list):
            raise ValueError('invalid compiler ABI')
        abipath = HERE / 'abi' / f'{name}.abi.json'
        abipath.write_text(json.dumps(abi, indent=2) + '\n')
        raw = pathlib.Path(tmp) / (stem + '.go')
        subprocess.run([abigen, '--abi', str(abipath), '--pkg', 'contracts', '--type', name, '--out', str(raw)], check=True)
        s = raw.read_text()
        marker = re.search('^var ' + name + 'MetaData = &bind.MetaData\\{', s, re.M)
        if not marker:
            raise ValueError('unsupported abigen metadata')
        structs = re.findall('^type (\\w+) struct \\{\\n.*?^\\}', s[:marker.start()], re.M | re.S)
        declarations = re.findall('^type \\w+ struct \\{\\n.*?^\\}', s[:marker.start()], re.M | re.S)
        compact = json.dumps(abi, separators=(',', ':'))
        pure = '// Code generated by generate.py; DO NOT EDIT.\npackage contracts\nimport("math/big";"github.com/ethereum/go-ethereum/common")\n' + '\n\n'.join(declarations) + f'\nvar {name}MetaData = &MetaData{{ABI:{json.dumps(compact)}}}\nvar {name}ABI = {name}MetaData.ABI\n'
        (HERE / (stem + '.go')).write_text(pure)
        for declaration, typename in zip(declarations, structs):
            s = s.replace(declaration, 'type ' + typename + ' = protocolcontracts.' + typename)
        s = s.replace('import (', 'import (\nprotocolcontracts "github.com/invisi-lab/invisi-sdk-go/protocol/contracts"', 1)
        s = re.sub('var ' + name + 'MetaData = &bind.MetaData\\{.*?\\n\\}', f'var {name}MetaData = &bind.MetaData{{ABI:protocolcontracts.{name}MetaData.ABI}}', s, count=1, flags=re.S)
        (network / (stem + '.go')).write_text(s)
formatter = shutil.which('goimports') or str(pathlib.Path.home() / 'go/bin/goimports')
subprocess.run([formatter, '-w', *[str(HERE / (stem + '.go')) for stem in names.values()], *[str(network / (stem + '.go')) for stem in names.values()]], check=True)
